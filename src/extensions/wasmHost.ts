import type { WasmPluginAbi } from "../../extensions/api";

// Minimal module: memory plus name_ptr/name_len pointing at "telemetry-echo".
const PROBE = new Uint8Array([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, 0x01, 0x05, 0x01, 0x60, 0x00, 0x01, 0x7f, 0x03, 0x03, 0x02, 0x00, 0x00, 0x05, 0x03, 0x01, 0x00, 0x01, 0x07, 0x20, 0x03, 0x06, 0x6d, 0x65, 0x6d, 0x6f, 0x72, 0x79, 0x02, 0x00, 0x08, 0x6e, 0x61, 0x6d, 0x65, 0x5f, 0x70, 0x74, 0x72, 0x00, 0x00, 0x08, 0x6e, 0x61, 0x6d, 0x65, 0x5f, 0x6c, 0x65, 0x6e, 0x00, 0x01, 0x0a, 0x0b, 0x02, 0x04, 0x00, 0x41, 0x00, 0x0b, 0x04, 0x00, 0x41, 0x0e, 0x0b, 0x0b, 0x14, 0x01, 0x00, 0x41, 0x00, 0x0b, 0x0e, 0x74, 0x65, 0x6c, 0x65, 0x6d, 0x65, 0x74, 0x72, 0x79, 0x2d, 0x65, 0x63, 0x68, 0x6f,
]);

export async function loadProbeWasm(): Promise<string> {
  const mod = await WebAssembly.instantiate(PROBE);
  const wasm = mod.instance.exports as unknown as WasmPluginAbi;
  const bytes = new Uint8Array(wasm.memory.buffer, wasm.name_ptr(), wasm.name_len());
  return new TextDecoder().decode(bytes);
}
